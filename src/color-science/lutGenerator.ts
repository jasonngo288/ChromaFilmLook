import { FilmEmulationProfile } from './types.ts';
import { transformPixel } from './transferFunctions.ts';

// Generates standard Adobe / DaVinci Resolve .cube 3D LUT string
export function generateCubeLUT(profile: FilmEmulationProfile, lutSize = 33, intensity = 1.0): string {
  const lines: string[] = [];
  lines.push(`# Title: ${profile.name} Film Emulation 3D LUT`);
  lines.push(`# Generated by ChromaFilm Color Science Studio`);
  lines.push(`# Manufacturer: ${profile.manufacturer}`);
  lines.push(`# Target Color Space: ${profile.targetColorSpace}`);
  lines.push(`# Applied LUT Intensity: ${(intensity * 100).toFixed(0)}%`);
  lines.push(`# Sensitometry Toe Lift: ${profile.sensitometry.toeLift.toFixed(4)}, Gamma: ${profile.sensitometry.midtoneContrast.toFixed(4)}`);
  lines.push(``);
  lines.push(`LUT_3D_SIZE ${lutSize}`);
  lines.push(`DOMAIN_MIN 0.0 0.0 0.0`);
  lines.push(`DOMAIN_MAX 1.0 1.0 1.0`);
  lines.push(``);

  // In .cube specification, Red index changes fastest, then Green, then Blue slowest:
  // for b = 0 to N-1
  //   for g = 0 to N-1
  //     for r = 0 to N-1
  const step = 1.0 / (lutSize - 1);

  for (let bIdx = 0; bIdx < lutSize; bIdx++) {
    const bIn = bIdx * step;
    for (let gIdx = 0; gIdx < lutSize; gIdx++) {
      const gIn = gIdx * step;
      for (let rIdx = 0; rIdx < lutSize; rIdx++) {
        const rIn = rIdx * step;

        const [rOut, gOut, bOut] = transformPixel(
          rIn,
          gIn,
          bIn,
          profile.sensitometry,
          profile.colorMatrix,
          profile.colorGrading,
          profile.targetColorSpace,
          intensity
        );

        lines.push(`${rOut.toFixed(6)} ${gOut.toFixed(6)} ${bOut.toFixed(6)}`);
      }
    }
  }

  return lines.join('\n');
}

// Generates standard HaldCLUT PNG bitmap on HTML5 Canvas
// Level 8 is the industry standard (512x512 pixels, 64^3 entries)
export function generateHaldClutCanvas(profile: FilmEmulationProfile, level = 8, intensity = 1.0): HTMLCanvasElement {
  // Level L: dimension is L^3 pixels wide and tall
  // Level 8: 8^3 = 512 x 512
  const cubeDim = level * level; // 64
  const imageDim = cubeDim * level; // 8 * 64 = 512
  const canvas = document.createElement('canvas');
  canvas.width = imageDim;
  canvas.height = imageDim;
  const ctx = canvas.getContext('2d');
  if (!ctx) return canvas;

  const imgData = ctx.createImageData(imageDim, imageDim);
  const data = imgData.data;

  // Standard HaldCLUT arrangement:
  // An identity Hald image is organized into level x level tiles, each cubeDim x cubeDim
  // Blue varies across tiles, Green varies vertically in tiles, Red varies horizontally
  const step = 1.0 / (cubeDim - 1);

  for (let y = 0; y < imageDim; y++) {
    for (let x = 0; x < imageDim; x++) {
      // Decode identity R, G, B coordinate for HaldCLUT pixel (x, y)
      const tileX = Math.floor(x / cubeDim);
      const tileY = Math.floor(y / cubeDim);
      const tileIdx = tileY * level + tileX; // 0 to level^2 - 1

      const inTileX = x % cubeDim;
      const inTileY = y % cubeDim;

      const rIn = inTileX * step;
      const gIn = inTileY * step;
      const bIn = tileIdx * step;

      // Transform through color science model with intensity
      const [rOut, gOut, bOut] = transformPixel(
        rIn,
        gIn,
        bIn,
        profile.sensitometry,
        profile.colorMatrix,
        profile.colorGrading,
        profile.targetColorSpace,
        intensity
      );

      const offset = (y * imageDim + x) * 4;
      data[offset] = Math.round(rOut * 255);
      data[offset + 1] = Math.round(gOut * 255);
      data[offset + 2] = Math.round(bOut * 255);
      data[offset + 3] = 255; // Alpha
    }
  }

  ctx.putImageData(imgData, 0, 0);
  return canvas;
}

export function downloadTextFile(content: string, filename: string, mimeType = 'text/plain') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function downloadCanvasAsPng(canvas: HTMLCanvasElement, filename: string) {
  canvas.toBlob((blob) => {
    if (!blob) return;
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }, 'image/png');
}
