import { FilmEmulationProfile } from './types.ts';

export function generatePythonCode(profile: FilmEmulationProfile): string {
  const m = profile.colorMatrix;
  const s = profile.sensitometry;
  const g = profile.colorGrading;
  const o = profile.opticalArtifacts;

  return `#!/usr/bin/env python3
"""
${profile.name} Film Emulation Engine
Generated by ChromaFilm Color Science Studio
Target Stock: ${profile.name} (${profile.manufacturer})
Target Space: ${profile.targetColorSpace}

Dependencies:
  pip install numpy opencv-python pillow
"""

import os
import argparse
import numpy as np
import cv2
from PIL import Image

# ---------------------------------------------------------
# Sensitometry & Spectral Parameters
# ---------------------------------------------------------
COLOR_MATRIX = np.array([
    [${m[0][0].toFixed(4)}, ${m[0][1].toFixed(4)}, ${m[0][2].toFixed(4)}],
    [${m[1][0].toFixed(4)}, ${m[1][1].toFixed(4)}, ${m[1][2].toFixed(4)}],
    [${m[2][0].toFixed(4)}, ${m[2][1].toFixed(4)}, ${m[2][2].toFixed(4)}]
], dtype=np.float32)

TOE_LIFT = ${s.toeLift.toFixed(4)}
SHADOW_GAMMA = ${s.shadowGamma.toFixed(4)}
MIDTONE_CONTRAST = ${s.midtoneContrast.toFixed(4)}
SHOULDER_ROLLOFF = ${s.shoulderRollOff.toFixed(4)}
HIGHLIGHT_CLIP = ${s.highlightClip.toFixed(4)}

SHADOW_TINT = np.array([${g.shadowTint.r.toFixed(4)}, ${g.shadowTint.g.toFixed(4)}, ${g.shadowTint.b.toFixed(4)}], dtype=np.float32)
HIGHLIGHT_TINT = np.array([${g.highlightTint.r.toFixed(4)}, ${g.highlightTint.g.toFixed(4)}, ${g.highlightTint.b.toFixed(4)}], dtype=np.float32)
GLOBAL_SATURATION = ${g.globalSaturation.toFixed(4)}
SHADOW_SATURATION = ${g.shadowSaturation.toFixed(4)}
HIGHLIGHT_SATURATION = ${g.highlightSaturation.toFixed(4)}

HALATION_INTENSITY = ${o.halationIntensity.toFixed(4)}
HALATION_THRESHOLD = ${o.halationThreshold.toFixed(4)}
GRAIN_INTENSITY = ${o.grainIntensity.toFixed(4)}

LUMA_WEIGHTS = np.array([0.2126, 0.7152, 0.0722], dtype=np.float32)


def evaluate_sensitometric_curve(x: np.ndarray) -> np.ndarray:
    """
    Evaluates Hurter-Driffield (H&D) sensitometric density curve:
    Includes soft toe flare, linear midtone gamma, and algebraic sigmoid shoulder.
    """
    clamped = np.clip(x, 0.0, 1.0)
    
    # 1. Toe Compression (shadow density / flare)
    toe_weight = np.exp(-clamped * (6.0 * SHADOW_GAMMA))
    toe = TOE_LIFT * toe_weight

    # 2. Midtone Linear Contrast
    midtone = 0.5 + (clamped - 0.5) * MIDTONE_CONTRAST

    # 3. Shoulder Soft Highlight Roll-Off
    shoulder_knee = 0.65
    k = 1.5 * SHOULDER_ROLLOFF
    
    # Vectorized piecewise shoulder compression
    mask = midtone > shoulder_knee
    shoulder = midtone.copy()
    if np.any(mask):
        excess = (midtone[mask] - shoulder_knee) / (1.0 - shoulder_knee)
        compressed = excess / ((1.0 + excess**k) ** (1.0 / k))
        shoulder[mask] = shoulder_knee + compressed * (HIGHLIGHT_CLIP - shoulder_knee)

    result = toe + shoulder * (1.0 - toe)
    return np.clip(result, 0.0, HIGHLIGHT_CLIP)


def apply_film_transform(rgb_float: np.ndarray) -> np.ndarray:
    """
    Transforms float RGB array [0.0, 1.0] through the full color science pipeline.
    Shape: (H, W, 3) or (N, 3)
    """
    # 1. Spectral Dye Coupler Matrix
    transformed = np.matmul(rgb_float, COLOR_MATRIX.T)
    transformed = np.clip(transformed, 0.0, 1.0)

    # 2. Sensitometric Curve (per-channel)
    transformed = evaluate_sensitometric_curve(transformed)

    # 3. Split-Tone Color Balance
    luma = np.dot(transformed, LUMA_WEIGHTS)[..., np.newaxis]
    shadow_weight = (1.0 - luma) ** 2.0
    highlight_weight = luma ** 2.0

    transformed += SHADOW_TINT * shadow_weight + HIGHLIGHT_TINT * highlight_weight

    # 4. Luminance-dependent Saturation
    midtone_weight = np.sin(luma * np.pi)
    sat_factor = GLOBAL_SATURATION * (
        SHADOW_SATURATION * shadow_weight +
        1.0 * midtone_weight +
        HIGHLIGHT_SATURATION * highlight_weight
    )
    transformed = luma + (transformed - luma) * sat_factor

    return np.clip(transformed, 0.0, 1.0)


def export_cube_lut(filepath: str, lut_size: int = 33):
    """
    Generates standard Adobe / DaVinci Resolve .cube 3D LUT.
    """
    print(f"[Color Science] Generating {lut_size}x{lut_size}x{lut_size} .cube LUT...")
    step = 1.0 / (lut_size - 1)
    
    with open(filepath, "w") as f:
        f.write(f"# Title: ${profile.name}\\n")
        f.write(f"# Generated by ChromaFilm Color Science Studio\\n")
        f.write(f"LUT_3D_SIZE {lut_size}\\n")
        f.write(f"DOMAIN_MIN 0.0 0.0 0.0\\n")
        f.write(f"DOMAIN_MAX 1.0 1.0 1.0\\n\\n")

        # In .cube spec: Blue outer, Green middle, Red inner
        for b in range(lut_size):
            b_val = b * step
            for g in range(lut_size):
                g_val = g * step
                for r in range(lut_size):
                    r_val = r * step
                    in_rgb = np.array([r_val, g_val, b_val], dtype=np.float32)
                    out_rgb = apply_film_transform(in_rgb)
                    f.write(f"{out_rgb[0]:.6f} {out_rgb[1]:.6f} {out_rgb[2]:.6f}\\n")
                    
    print(f"[Color Science] Saved LUT to: {filepath}")


def export_hald_clut(filepath: str, level: int = 8):
    """
    Generates standard HaldCLUT PNG matrix (Level 8 = 512x512 = 64^3 nodes).
    Compatible with ImageMagick and RawTherapee.
    """
    print(f"[Color Science] Generating HaldCLUT Level {level} PNG...")
    cube_dim = level * level      # 64
    img_dim = cube_dim * level    # 512
    step = 1.0 / (cube_dim - 1)

    hald = np.zeros((img_dim, img_dim, 3), dtype=np.float32)

    for y in range(img_dim):
        for x in range(img_dim):
            tile_x = x // cube_dim
            tile_y = y // cube_dim
            tile_idx = tile_y * level + tile_x

            r_in = (x % cube_dim) * step
            g_in = (y % cube_dim) * step
            b_in = tile_idx * step

            hald[y, x] = [r_in, g_in, b_in]

    # Transform entire Hald image through color science engine
    graded_hald = apply_film_transform(hald)
    hald_uint8 = np.clip(graded_hald * 255.0 + 0.5, 0, 255).astype(np.uint8)

    # Convert RGB to BGR for OpenCV or save directly with PIL
    pil_img = Image.fromarray(hald_uint8)
    pil_img.save(filepath, format="PNG")
    print(f"[Color Science] Saved HaldCLUT to: {filepath}")


def process_image(input_path: str, output_path: str):
    """
    Applies the full film emulation look to an image using OpenCV & NumPy.
    """
    print(f"[Color Science] Reading image: {input_path}")
    bgr = cv2.imread(input_path, cv2.IMREAD_COLOR)
    if bgr is None:
        raise FileNotFoundError(f"Could not load image at {input_path}")

    # Convert BGR uint8 -> RGB float32 [0.0, 1.0]
    rgb = cv2.cvtColor(bgr, cv2.COLOR_BGR2RGB).astype(np.float32) / 255.0

    # Apply core color science transform
    graded = apply_film_transform(rgb)

    # Optical Artifact 1: Halation (red scatter around highlights)
    if HALATION_INTENSITY > 0.01:
        luma = np.dot(graded, LUMA_WEIGHTS)
        high_mask = np.clip((luma - HALATION_THRESHOLD) / (1.0 - HALATION_THRESHOLD), 0.0, 1.0)
        # Red-shifted blur
        blurred_mask = cv2.GaussianBlur(high_mask, (15, 15), 5.0)
        graded[:, :, 0] += blurred_mask * HALATION_INTENSITY * 0.8
        graded[:, :, 1] += blurred_mask * HALATION_INTENSITY * 0.2

    # Optical Artifact 2: Silver Halide Film Grain
    if GRAIN_INTENSITY > 0.01:
        h, w, _ = graded.shape
        noise = np.random.normal(0.0, GRAIN_INTENSITY * 0.5, (h, w, 1)).astype(np.float32)
        # Film grain is most visible in midtones, less in extreme highlights
        luma = np.dot(graded, LUMA_WEIGHTS)[..., np.newaxis]
        grain_scale = np.sin(luma * np.pi)
        graded += noise * grain_scale

    graded = np.clip(graded, 0.0, 1.0)

    # Convert back to uint8 BGR
    out_bgr = cv2.cvtColor((graded * 255.0 + 0.5).astype(np.uint8), cv2.COLOR_RGB2BGR)
    cv2.imwrite(output_path, out_bgr)
    print(f"[Color Science] Successfully saved graded output to: {output_path}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="${profile.name} Color Science Pipeline")
    parser.add_argument("--input", type=str, help="Path to input image")
    parser.add_argument("--output", type=str, default="graded_output.jpg", help="Path to output image")
    parser.add_argument("--export-cube", type=str, default="${profile.id}.cube", help="Path to export .cube 3D LUT")
    parser.add_argument("--export-hald", type=str, default="${profile.id}_hald8.png", help="Path to export HaldCLUT PNG")
    parser.add_argument("--lut-size", type=int, default=33, help="3D LUT resolution (e.g. 17, 33, 65)")
    args = parser.parse_args()

    if args.export_cube:
        export_cube_lut(args.export_cube, lut_size=args.lut_size)
    if args.export_hald:
        export_hald_clut(args.export_hald, level=8)
    if args.input:
        process_image(args.input, args.output)
`;
}

export function generateGLSLCode(profile: FilmEmulationProfile): string {
  const m = profile.colorMatrix;
  const s = profile.sensitometry;
  const g = profile.colorGrading;
  const o = profile.opticalArtifacts;

  return `// ====================================================================
// ${profile.name} Film Emulation Fragment Shader (GLSL ES 3.0 / WebGL 2)
// Generated by ChromaFilm Color Science Studio
// ====================================================================
#version 300 es
precision highp float;

in vec2 v_texCoord;
out vec4 fragColor;

uniform sampler2D u_image;
uniform vec2 u_resolution;
uniform float u_time;

// Sensitometry Constants
const float TOE_LIFT = ${s.toeLift.toFixed(4)};
const float SHADOW_GAMMA = ${s.shadowGamma.toFixed(4)};
const float MIDTONE_CONTRAST = ${s.midtoneContrast.toFixed(4)};
const float SHOULDER_ROLLOFF = ${s.shoulderRollOff.toFixed(4)};
const float HIGHLIGHT_CLIP = ${s.highlightClip.toFixed(4)};

// Dye Coupler Spectral Matrix (3x3)
const mat3 COLOR_MATRIX = mat3(
    ${m[0][0].toFixed(4)}, ${m[1][0].toFixed(4)}, ${m[2][0].toFixed(4)},
    ${m[0][1].toFixed(4)}, ${m[1][1].toFixed(4)}, ${m[2][1].toFixed(4)},
    ${m[0][2].toFixed(4)}, ${m[1][2].toFixed(4)}, ${m[2][2].toFixed(4)}
);

// Split Toning & Saturation
const vec3 SHADOW_TINT = vec3(${g.shadowTint.r.toFixed(4)}, ${g.shadowTint.g.toFixed(4)}, ${g.shadowTint.b.toFixed(4)});
const vec3 HIGHLIGHT_TINT = vec3(${g.highlightTint.r.toFixed(4)}, ${g.highlightTint.g.toFixed(4)}, ${g.highlightTint.b.toFixed(4)});
const float GLOBAL_SATURATION = ${g.globalSaturation.toFixed(4)};
const float SHADOW_SATURATION = ${g.shadowSaturation.toFixed(4)};
const float HIGHLIGHT_SATURATION = ${g.highlightSaturation.toFixed(4)};

const vec3 LUMA = vec3(0.2126, 0.7152, 0.0722);

// Pseudo-random noise for silver halide film grain
float hash(vec2 p) {
    p = fract(p * vec2(123.34, 456.21));
    p += dot(p, p + 45.32);
    return fract(p.x * p.y);
}

// Sensitometric Hurter-Driffield (H&D) transfer function
float evaluateSensitometry(float x) {
    float clamped = clamp(x, 0.0, 1.0);

    // 1. Toe Compression
    float toeWeight = exp(-clamped * (6.0 * SHADOW_GAMMA));
    float toe = TOE_LIFT * toeWeight;

    // 2. Straight-line Midtone Gamma
    float midtone = 0.5 + (clamped - 0.5) * MIDTONE_CONTRAST;

    // 3. Highlight Soft Shoulder Roll-off (Algebraic Sigmoid)
    float shoulderKnee = 0.65;
    float k = 1.5 * SHOULDER_ROLLOFF;
    float shoulder = midtone;

    if (midtone > shoulderKnee) {
        float excess = (midtone - shoulderKnee) / (1.0 - shoulderKnee);
        float compressed = excess / pow(1.0 + pow(excess, k), 1.0 / k);
        shoulder = shoulderKnee + compressed * (HIGHLIGHT_CLIP - shoulderKnee);
    }

    float res = toe + shoulder * (1.0 - toe);
    return clamp(res, 0.0, HIGHLIGHT_CLIP);
}

vec3 applySensitometry(vec3 rgb) {
    return vec3(
        evaluateSensitometry(rgb.r),
        evaluateSensitometry(rgb.g),
        evaluateSensitometry(rgb.b)
    );
}

void main() {
    vec4 src = texture(u_image, v_texCoord);
    vec3 rgb = clamp(src.rgb, 0.0, 1.0);

    // 1. Spectral Dye Coupler Matrix
    rgb = clamp(COLOR_MATRIX * rgb, 0.0, 1.0);

    // 2. Sensitometric Curves
    rgb = applySensitometry(rgb);

    // 3. Split-Tone Color Balance
    float lum = dot(rgb, LUMA);
    float shadowWeight = pow(1.0 - lum, 2.0);
    float highlightWeight = pow(lum, 2.0);
    rgb += SHADOW_TINT * shadowWeight + HIGHLIGHT_TINT * highlightWeight;

    // 4. Luminance-dependent Saturation
    float midtoneWeight = sin(lum * 3.14159265);
    float effectiveSat = GLOBAL_SATURATION * (
        SHADOW_SATURATION * shadowWeight +
        1.0 * midtoneWeight +
        HIGHLIGHT_SATURATION * highlightWeight
    );
    rgb = mix(vec3(lum), rgb, effectiveSat);

    // 5. Procedural Silver Halide Film Grain
    #if ${o.grainIntensity > 0.01 ? '1' : '0'}
    float grain = (hash(v_texCoord * u_resolution + fract(u_time)) - 0.5) * ${o.grainIntensity.toFixed(4)};
    float grainScale = sin(lum * 3.14159265);
    rgb += vec3(grain * grainScale);
    #endif

    fragColor = vec4(clamp(rgb, 0.0, 1.0), src.a);
}
`;
}

export function generateMetalCode(profile: FilmEmulationProfile): string {
  const m = profile.colorMatrix;
  const s = profile.sensitometry;
  const g = profile.colorGrading;

  return `// ====================================================================
// ${profile.name} Film Emulation Kernel (Apple Metal Shading Language - MSL)
// Generated by ChromaFilm Color Science Studio
// Compatible with Metal 2.0+ on iOS, iPadOS, macOS
// ====================================================================

#include <metal_stdlib>
using namespace metal;

struct FilmParameters {
    float3x3 colorMatrix;
    float toeLift;
    float shadowGamma;
    float midtoneContrast;
    float shoulderRollOff;
    float highlightClip;
    float3 shadowTint;
    float3 highlightTint;
    float globalSaturation;
    float shadowSaturation;
    float highlightSaturation;
};

// Sensitometric density curve mapping
inline float evaluateSensitometricCurve(float x, constant FilmParameters& p) {
    float clamped = clamp(x, 0.0f, 1.0f);
    
    // Toe flare
    float toeWeight = exp(-clamped * (6.0f * p.shadowGamma));
    float toe = p.toeLift * toeWeight;

    // Midtone contrast
    float midtone = 0.5f + (clamped - 0.5f) * p.midtoneContrast;

    // Shoulder sigmoid roll-off
    float shoulderKnee = 0.65f;
    float k = 1.5f * p.shoulderRollOff;
    float shoulder = midtone;

    if (midtone > shoulderKnee) {
        float excess = (midtone - shoulderKnee) / (1.0f - shoulderKnee);
        float compressed = excess / pow(1.0f + pow(excess, k), 1.0f / k);
        shoulder = shoulderKnee + compressed * (p.highlightClip - shoulderKnee);
    }

    return clamp(toe + shoulder * (1.0f - toe), 0.0f, p.highlightClip);
}

kernel void filmEmulationKernel(
    texture2d<float, access::read> inTexture [[texture(0)]],
    texture2d<float, access::write> outTexture [[texture(1)]],
    constant FilmParameters& params [[buffer(0)]],
    uint2 gid [[thread_position_in_grid]])
{
    if (gid.x >= outTexture.get_width() || gid.y >= outTexture.get_height()) {
        return;
    }

    float4 inColor = inTexture.read(gid);
    float3 rgb = clamp(inColor.rgb, 0.0f, 1.0f);

    // 1. Spectral Dye Coupler Matrix
    rgb = clamp(params.colorMatrix * rgb, 0.0f, 1.0f);

    // 2. Sensitometric Curves
    rgb.r = evaluateSensitometricCurve(rgb.r, params);
    rgb.g = evaluateSensitometricCurve(rgb.g, params);
    rgb.b = evaluateSensitometricCurve(rgb.b, params);

    // 3. Split-Tone Color Balance
    const float3 lumaWeights = float3(0.2126f, 0.7152f, 0.0722f);
    float lum = dot(rgb, lumaWeights);
    float shadowWeight = pow(1.0f - lum, 2.0f);
    float highlightWeight = pow(lum, 2.0f);
    rgb += params.shadowTint * shadowWeight + params.highlightTint * highlightWeight;

    // 4. Saturation
    float midtoneWeight = sin(lum * 3.14159265f);
    float effectiveSat = params.globalSaturation * (
        params.shadowSaturation * shadowWeight +
        1.0f * midtoneWeight +
        params.highlightSaturation * highlightWeight
    );
    rgb = mix(float3(lum), rgb, effectiveSat);

    outTexture.write(float4(clamp(rgb, 0.0f, 1.0f), inColor.a), gid);
}
`;
}

export function generateCoreImageCode(profile: FilmEmulationProfile): string {
  const m = profile.colorMatrix;
  const s = profile.sensitometry;
  const g = profile.colorGrading;

  return `// ====================================================================
// ${profile.name} Apple CoreImage (CIColorKernel in Swift)
// Drop directly into iOS / macOS CoreImage pipeline
// ====================================================================

import CoreImage

class ${profile.id.replace(/[^a-zA-Z0-9]/g, '')}FilmFilter: CIFilter {
    @objc dynamic var inputImage: CIImage?

    static let metalKernel: CIColorKernel = {
        let kernelString = """
        #include <CoreImage/CoreImage.h>
        using namespace metal;

        [[stitchable]] float4 ${profile.id.replace(/[^a-zA-Z0-9]/g, '')}Kernel(coreimage::sample_t s) {
            float3 rgb = clamp(s.rgb, 0.0, 1.0);

            // Dye Coupler Matrix
            float3x3 m = float3x3(
                float3(${m[0][0].toFixed(4)}, ${m[1][0].toFixed(4)}, ${m[2][0].toFixed(4)}),
                float3(${m[0][1].toFixed(4)}, ${m[1][1].toFixed(4)}, ${m[2][1].toFixed(4)}),
                float3(${m[0][2].toFixed(4)}, ${m[1][2].toFixed(4)}, ${m[2][2].toFixed(4)})
            );
            rgb = clamp(m * rgb, 0.0, 1.0);

            // Sensitometry: Midtone Contrast & Shoulder
            float mid = 0.5 + (rgb.r - 0.5) * ${s.midtoneContrast.toFixed(4)};
            float toe = ${s.toeLift.toFixed(4)} * exp(-rgb.r * 6.0);
            rgb = clamp(toe + mid * (1.0 - toe), 0.0, ${s.highlightClip.toFixed(4)});

            // Color Split Tone
            float lum = dot(rgb, float3(0.2126, 0.7152, 0.0722));
            rgb += float3(${g.shadowTint.r.toFixed(4)}, ${g.shadowTint.g.toFixed(4)}, ${g.shadowTint.b.toFixed(4)}) * pow(1.0 - lum, 2.0);

            // Saturation
            rgb = mix(float3(lum), rgb, ${g.globalSaturation.toFixed(4)});

            return float4(clamp(rgb, 0.0, 1.0), s.a);
        }
        """
        guard let kernel = try? CIColorKernel(functionName: "${profile.id.replace(/[^a-zA-Z0-9]/g, '')}Kernel", fromMetalLibraryData: Data()) else {
            fatalError("Failed to compile CIColorKernel")
        }
        return kernel
    }()

    override var outputImage: CIImage? {
        guard let inputImage = inputImage else { return nil }
        return ${profile.id.replace(/[^a-zA-Z0-9]/g, '')}FilmFilter.metalKernel.apply(extent: inputImage.extent, arguments: [inputImage])
    }
}
`;
}
